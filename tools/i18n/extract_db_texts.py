#!/usr/bin/env python3
"""Lists the database texts shown in the game, for the Qt translation.

The template database keeps its texts in English. This script writes
them to stargate/src/db/dbtexts_i18n.h as QT_TRANSLATE_NOOP("Database",
...) entries; lupdate then adds them to stargate_fr.ts and the game
translates them when they are shown (DbText::tr).

Run it after changing texts in the database (quests, ships…):
    python3 tools/i18n/extract_db_texts.py
    lupdate stargate/stargate.pro
"""
import pathlib
import sqlite3

ROOT = pathlib.Path(__file__).resolve().parents[2]
DB = ROOT / "stargate/src/db/stagateDataBase.db"
OUT = ROOT / "stargate/src/db/dbtexts_i18n.h"

QUERIES = [
    ("Quests", "SELECT title FROM Quest UNION ALL SELECT description FROM Quest"),
    ("Quest objectives", "SELECT description FROM Quest_Objective"),
    ("Resources", "SELECT name FROM Resource UNION ALL SELECT description FROM Resource"
                  " UNION ALL SELECT lower(rarity) FROM Resource"),
    ("Ship components", "SELECT name FROM Component"),
    ("Ship library", "SELECT description FROM Ship_Type UNION ALL SELECT name FROM Ship_Attack"
                     " UNION ALL SELECT description FROM Ship_Attack"),
]


def cpp_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    seen = set()
    lines = [
        "// Generated by tools/i18n/extract_db_texts.py - do not edit.",
        "// Database texts for lupdate (never compiled): translated at display",
        "// time with DbText::tr (context \"Database\").",
        "#if 0",
    ]
    for title, query in QUERIES:
        lines.append(f"// {title}")
        for (text,) in con.execute(query):
            if text and text.strip() and text not in seen:
                seen.add(text)
                lines.append(f'QT_TRANSLATE_NOOP("Database", {cpp_string(text)})')
    lines.append("#endif")
    OUT.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
    print(f"{len(seen)} texts -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
